#!/usr/bin/env python3
"""Read-only mapping preview: legacy `carte_grises` (vehicule.sql) -> `vehicles` schema.

Does NOT touch any database and does NOT modify vehicule.sql. It parses the
legacy dump (reusing read_vehicule_sql.py's parser), maps each row's columns
onto the CURRENT `Vehicle` model's column names (app/models.py), and writes
the result to a new CSV file for review. Fields with no reliable legacy
source are left blank.

Mapping used (legacy -> vehicles):
    Num_Matricule       -> license_plate
    Nom                 -> owner_name
    Adresse             -> owner_address
    Commune             -> owner_island   (Ngazidja/Nzwani/Mwali -> Grande Comore/Anjouan/Moheli)
    Genre               -> vehicle_type   (normalisé vers les codes de l'app : voiture/pickup/moto/
                                            camion/minibus/bus/ambulance/suv/other ; les 'voiture'
                                            sont affinés en suv/pickup/minibus via Marque+Sous_Marque)
    Marque              -> make           (marque seule, ex. 'RENAULT  KANGOO' -> 'RENAULT')
    Sous_Marque         -> model
    Nbre_CVX            -> nombre_chevaux
    Num_serie           -> vin
    Source_Energie      -> fuel_type      (Essance -> Essence, GasOil -> Gazoil)
    Date_delivrance     -> registration_date
    Per_Annee_MC        -> year           (date de première mise en circulation ; on n'en garde
                                            que l'année, avec correction des années à 5-6 chiffres
                                            causées par un chiffre parasite saisi en trop ; les
                                            années hors 1950-2026, ou non résolvables, sont laissées
                                            vides plutôt que de deviner)
    Observation         -> notes
    Nom_Agent           -> created_by

Extra columns (not on `Vehicle` itself, but on the linked `CarteGrise` model
— appended after the vehicles columns so they aren't lost):
    Nombre_Place        -> places_assises
    Poids_TAC           -> poids_total_autorise
    Poids_vide          -> poids_a_vide
    Charge_Utile        -> charge_utile_ptc
    Profession          -> profession_proprietaire

Everything else in the `vehicles` schema (status, fiscal_class, cv_class,
insurance_*, vignette_*, qr_code_*, track_token, id, ...) has no legacy
equivalent and is left empty in the output CSV.

Usage:
    python3 map_vehicule_to_vehicles.py [path/to/vehicule.sql] [-o out.csv]
"""
