def extract_make(marque):
    """Pull just the manufacturer name out of `Marque`, which mixes make+model
    (e.g. 'RENAULT  KANGOO' -> 'RENAULT', 'MERCEDES  BENZ  CLASSE' -> 'MERCEDES BENZ')."""
    marque = clean(marque)
    if not marque:
        return ""
    tokens = marque.upper().split()
    if not tokens:
        return ""
    if len(tokens) >= 2 and (tokens[0], tokens[1]) in MULTI_WORD_MAKES:
        return MULTI_WORD_MAKES[(tokens[0], tokens[1])]
    if (tokens[0],) in MULTI_WORD_MAKES:
        return MULTI_WORD_MAKES[(tokens[0],)]
    if tokens[0] == "MERCEDES":
        return "MERCEDES BENZ"
    return tokens[0]


