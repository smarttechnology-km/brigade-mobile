def map_row(legacy):
    row = {col: "" for col in VEHICLE_COLUMNS + CARTE_GRISE_COLUMNS}
    # [:N] truncations mirror the Vehicle/CarteGrise column limits in
    # app/models.py — a safety net so a corrupted legacy value (e.g. a name
    # padded/duplicated into a 255-char field) can never overflow a Postgres
    # varchar column and crash the whole import, even if some future row
    # slips past the cleaning above.
    row["license_plate"] = (legacy.get("Num_Matricule") or "").strip()[:20]
    row["owner_name"] = dedupe_repeated_name(clean(legacy.get("Nom")))[:100]
    row["owner_address"] = clean(legacy.get("Adresse"))[:255]
    row["owner_island"] = map_island(legacy.get("Commune"))[:50]
    row["vehicle_type"] = classify_vehicle_type(
        legacy.get("Genre"), legacy.get("Marque"), legacy.get("Sous_Marque")
    )
    row["make"] = extract_make(legacy.get("Marque"))[:50]
    row["model"] = clean(legacy.get("Sous_Marque"))[:50]
    row["nombre_chevaux"] = clean(legacy.get("Nbre_CVX"))
    row["vin"] = clean(legacy.get("Num_serie"))[:50]
    row["fuel_type"] = map_fuel(legacy.get("Source_Energie"))[:50]
    row["registration_date"] = map_date(legacy.get("Date_delivrance"))
    plate = (legacy.get("Num_Matricule") or "").strip()
    row["year"] = MANUAL_YEAR_OVERRIDES.get(plate) or extract_year(legacy.get("Per_Annee_MC"))
    row["notes"] = clean(legacy.get("Observation"))
    row["created_by"] = clean(legacy.get("Nom_Agent"))[:80]
    row["places_assises"] = clean(legacy.get("Nombre_Place"))[:20]
    row["poids_total_autorise"] = clean(legacy.get("Poids_TAC"))[:50]
    row["poids_a_vide"] = clean(legacy.get("Poids_vide"))[:50]
    row["charge_utile_ptc"] = clean(legacy.get("Charge_Utile"))[:50]
    row["profession_proprietaire"] = clean(legacy.get("Profession"))[:150]
    return row


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", nargs="?", default="vehicule.sql", help="Path to the .sql dump")
    parser.add_argument("-o", "--output", default="vehicules_mappes.csv", help="Fichier CSV de sortie")
    args = parser.parse_args()

    path = Path(args.path)
    if not path.exists():
        print(f"Fichier introuvable : {path}", file=sys.stderr)
        sys.exit(1)

    sql_text = path.read_text(encoding="utf-8", errors="replace")
    tables = parse_create_tables(sql_text)

    if SOURCE_TABLE not in tables:
        print(f"Table `{SOURCE_TABLE}` introuvable dans {path}", file=sys.stderr)
        sys.exit(1)

    cols = tables[SOURCE_TABLE]
    mapped_rows = []
    for table, values_blob in iter_insert_statements(sql_text):
        if table != SOURCE_TABLE:
            continue
        for tuple_body in split_top_level_tuples(values_blob):
            fields = [unquote(f) for f in split_fields(tuple_body)]
            legacy = dict(zip(cols, fields))
            mapped_rows.append(map_row(legacy))

    out_path = Path(args.output)
    with out_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=VEHICLE_COLUMNS + CARTE_GRISE_COLUMNS)
        writer.writeheader()
        writer.writerows(mapped_rows)

    print(f"{len(mapped_rows)} lignes mappées depuis `{SOURCE_TABLE}`.")
    print(f"Fichier écrit : {out_path.resolve()}")
    print("Aucune donnée n'a été écrite en base — c'est un fichier de relecture uniquement.")

    from collections import Counter
    type_counts = Counter(r["vehicle_type"] for r in mapped_rows)
    print("\nRépartition vehicle_type :")
    for cat, n in type_counts.most_common():
        print(f"  {cat:10s} {n}")

    year_resolved = sum(1 for r in mapped_rows if r["year"])
    print(f"\nAnnée (year) extraite pour {year_resolved}/{len(mapped_rows)} lignes "
          f"({len(mapped_rows) - year_resolved} laissées vides, valeur non fiable).")


if __name__ == "__main__":
    main()
