def classify_genre(genre):
    g = (genre or "").strip().upper()
    for kw, cat in GENRE_KEYWORDS:
        if kw in g:
            return cat
    # Everything else (VOITURE/V P/VP/VITURE/VOTURE typos, blank, or unknown
    # abbreviations like TCP/MTT2/TEM/VV) defaults to the generic car bucket,
    # which is then refined below using the make/model.
    return "voiture"


def classify_vehicle_type(genre, marque_raw, sous_marque):
    base = classify_genre(genre)
    if base != "voiture":
        return base
    combined = f"{clean(marque_raw)} {clean(sous_marque)}".upper()
    for kw in PICKUP_MODEL_KEYWORDS:
        if kw in combined:
            return "pickup"
    for kw in SUV_MODEL_KEYWORDS:
        if kw in combined:
            return "suv"
    for kw in MINIBUS_MODEL_KEYWORDS:
        if kw in combined:
            return "minibus"
    if extract_make(marque_raw) in SUV_ONLY_MAKES:
        return "suv"
    return "voiture"


