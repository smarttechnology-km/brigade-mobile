def map_fuel(source_energie):
    source_energie = clean(source_energie)
    if not source_energie:
        return ""
    key = source_energie.lower()
    return FUEL_MAP.get(key, source_energie)


def map_date(raw):
    """Legacy dates come as ' 30/10/2021' or '2008-11-17'. Normalize to YYYY-MM-DD, else keep raw."""
    if not raw:
        return ""
    raw = raw.strip()
    m = re.match(r"^(\d{2})/(\d{2})/(\d{4})$", raw)
    if m:
        d, mo, y = m.groups()
        return f"{y}-{mo}-{d}"
    if re.match(r"^\d{4}-\d{2}-\d{2}$", raw):
        return raw
    return raw


MIN_PLAUSIBLE_YEAR = 1950
MAX_PLAUSIBLE_YEAR = 2026


def extract_year(raw_date):
    """Pull just the year out of Per_Annee_MC (date de première mise en
    circulation). Some rows have a stray extra digit (typo) making the year
    5 or 6 digits, e.g. '22010-10-26' instead of '2010-10-26'. Try removing
    each possible single extra digit and keep the result only if exactly
    one position yields a plausible year — when several positions are
    plausible (e.g. '20012' could read as 2001, 2002 or 2012), it's
    genuinely ambiguous from the digits alone, so this returns blank rather
    than guessing (see MANUAL_YEAR_OVERRIDES for those, checked by hand).
    Anything outside 1950-2026 (placeholders like '0001-01-01', impossible
    dates like '1883-03-03') is also left blank."""
    if not raw_date:
        return ""
    m = re.match(r"^(\d+)-\d{2}-\d{2}$", raw_date.strip())
    if not m:
        return ""
    yr = m.group(1)

    def plausible(y):
        return len(y) == 4 and MIN_PLAUSIBLE_YEAR <= int(y) <= MAX_PLAUSIBLE_YEAR

    if len(yr) == 4:
        return yr if plausible(yr) else ""

    excess = len(yr) - 4
    if excess <= 0:
        return ""
    if excess == 1:
        candidates = {yr[:i] + yr[i + 1:] for i in range(len(yr))}
    else:
        candidates = {yr[excess:], yr[:-excess]}
    plausible_candidates = {c for c in candidates if plausible(c)}
    if len(plausible_candidates) == 1:
        return next(iter(plausible_candidates))
    return ""


