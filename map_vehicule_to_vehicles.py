SOURCE_TABLE = "carte_grises"

NONE_MARKERS = {"NEANT", "NÉANT"}


def clean(value):
    """Strip a legacy field, collapse internal runs of whitespace to a single
    space (some rows are padded to a fixed width, e.g. 255 chars, with
    trailing/internal spaces), and treat the 'NEANT' placeholder (used across
    many columns in vehicule.sql — Profession, Poids_TAC/vide, Charge_Utile,
    Sous_Marque, Marque, Commune — to mean "no value") as blank."""
    v = re.sub(r"\s+", " ", (value or "").strip())
    return "" if v.upper() in NONE_MARKERS else v


def dedupe_repeated_name(value):
    """Some legacy Nom values are the same name typed twice into a padded
    fixed-width field (e.g. 'DJAMAL ISSIMAIL ISSIHAKA' + spaces + itself
    again, 242 chars total) — long enough to overflow the 100-char
    owner_name column on import. If the whole value is two identical halves,
    collapse to one."""
    parts = value.split(" ")
    n = len(parts)
    if n >= 2 and n % 2 == 0:
        half = n // 2
        if parts[:half] == parts[half:]:
            return " ".join(parts[:half])
    return value

